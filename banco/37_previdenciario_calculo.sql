-- 37_previdenciario_calculo.sql — módulo Previdenciário, etapa 2: tabelas oficiais e simulações
--
-- O cálculo das aposentadorias roda na tela, mas os números oficiais moram aqui,
-- para que a atualização (manual ou pelo robô semanal) não exija republicar o sistema:
--   prev_parametro — salário mínimo e teto do RGPS, com a data em que cada valor começa;
--   prev_indice    — índice mensal de correção dos salários de contribuição (tabela oficial
--                    da Previdência) e INPC mensal (IBGE), que reajusta os benefícios;
--   prev_sobrevida — expectativa de sobrevida do IBGE (tábua de ambos os sexos), usada
--                    no fator previdenciário, com o período em que cada tábua vale;
--   prev_simulacao — o resultado de cada cálculo que se quis guardar, por análise.
--
-- As três primeiras são de referência, iguais para todo escritório: qualquer pessoa
-- logada lê; só o titular altera pela tela (o robô usa a chave de serviço).
-- Os valores abaixo foram conferidos na fonte oficial indicada em cada linha.

create table if not exists public.prev_parametro (
  id          uuid primary key default uuid_generate_v4(),
  tipo        text not null check (tipo in ('salario_minimo','teto')),
  inicio      date not null,
  valor       numeric(14,2) not null check (valor > 0),
  ato         text,
  fonte       text,
  atualizado_em timestamptz not null default now(),
  unique (tipo, inicio)
);

create table if not exists public.prev_indice (
  competencia date primary key,              -- dia 1º do mês
  inpc        numeric(8,4) not null,          -- variação mensal, em % (reajuste dos benefícios)
  correcao    numeric(12,6),                  -- índice mensal de correção dos salários de contribuição, em %
                                              -- (IPC-r, INPC e IGP-DI conforme a época), tirado da tabela oficial do art. 33
                                              -- do Decreto 3.048; sem ele, o sistema usa o INPC
  fonte       text,
  atualizado_em timestamptz not null default now()
);

create table if not exists public.prev_sobrevida (
  ano_tabua       integer not null,
  idade           integer not null,
  expectativa     numeric(5,2) not null,
  vigencia_inicio date not null,
  vigencia_fim    date,
  fonte           text,
  primary key (ano_tabua, idade)
);

create table if not exists public.prev_simulacao (
  id            uuid primary key default uuid_generate_v4(),
  escritorio_id uuid not null references public.escritorio(id) on delete cascade,
  analise_id    uuid not null references public.prev_analise(id) on delete cascade,
  data_base     date not null,
  opcoes        jsonb not null default '{}'::jsonb,
  resultado     jsonb not null,
  melhor        text,
  rmi           numeric(14,2),
  criado_em     timestamptz not null default now()
);
create index if not exists prev_sim_analise_idx on public.prev_simulacao(analise_id, criado_em desc);

alter table public.prev_parametro enable row level security;
alter table public.prev_indice    enable row level security;
alter table public.prev_sobrevida enable row level security;
alter table public.prev_simulacao enable row level security;

drop policy if exists prev_param_ler on public.prev_parametro;
create policy prev_param_ler on public.prev_parametro for select to authenticated using (true);
drop policy if exists prev_param_titular on public.prev_parametro;
create policy prev_param_titular on public.prev_parametro for all to authenticated
  using (meu_perfil() = 'titular') with check (meu_perfil() = 'titular');

drop policy if exists prev_indice_ler on public.prev_indice;
create policy prev_indice_ler on public.prev_indice for select to authenticated using (true);
drop policy if exists prev_indice_titular on public.prev_indice;
create policy prev_indice_titular on public.prev_indice for all to authenticated
  using (meu_perfil() = 'titular') with check (meu_perfil() = 'titular');

drop policy if exists prev_sobrevida_ler on public.prev_sobrevida;
create policy prev_sobrevida_ler on public.prev_sobrevida for select to authenticated using (true);
drop policy if exists prev_sobrevida_titular on public.prev_sobrevida;
create policy prev_sobrevida_titular on public.prev_sobrevida for all to authenticated
  using (meu_perfil() = 'titular') with check (meu_perfil() = 'titular');

drop policy if exists prev_sim_membro on public.prev_simulacao;
create policy prev_sim_membro on public.prev_simulacao for all
  using (escritorio_id = meu_escritorio()
         and exists (select 1 from public.prev_analise a where a.id = prev_simulacao.analise_id))
  with check (escritorio_id = meu_escritorio()
         and exists (select 1 from public.prev_analise a where a.id = prev_simulacao.analise_id));


